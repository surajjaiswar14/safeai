    val destinations: List<Destination> get() = allDestinationsList

    fun getSavedDestinations(): Flow<List<Destination>> {
        return dao.getAllSavedDestinations().map { savedList ->
            val savedIds = savedList.map { it.destinationId }.toSet()
            allDestinationsList.map { dest ->
                dest.copy(isSaved = savedIds.contains(dest.id))
            }
        }
    }

    fun getOfflinePacks(): Flow<List<Destination>> {
        return dao.getAllOfflinePacks().map { packList ->
            val downloadedIds = packList.map { it.destinationId }.toSet()
            allDestinationsList.filter { downloadedIds.contains(it.id) }.map {
                it.copy(isDownloaded = true)
            }
        }
    }

    suspend fun isDestinationSaved(id: String): Boolean {
        return dao.isDestinationSaved(id)
    }

    suspend fun toggleSaveDestination(id: String): Boolean {
        val currentlySaved = dao.isDestinationSaved(id)
        if (currentlySaved) {
            dao.deleteSavedDestination(id)
            return false
        } else {
            dao.insertSavedDestination(SavedDestinationEntity(destinationId = id))
            return true
        }
    }

    suspend fun isOfflinePackDownloaded(id: String): Boolean {
        return dao.isOfflinePackDownloaded(id)
    }

    suspend fun downloadOfflinePack(destination: Destination) {
        val jsonPayload = """{"id":"${destination.id}","name":"${destination.name}","safetyScore":${destination.safetyScore},"permitInfo":"${destination.permitInfo}"}"""
        val entity = OfflinePackEntity(
            destinationId = destination.id,
            name = destination.name,
            state = destination.state,
            jsonContent = jsonPayload,
            sizeKb = 450
        )
        dao.insertOfflinePack(entity)
    }

    suspend fun deleteOfflinePack(id: String) {
        dao.deleteOfflinePack(id)
    }

    fun getDestinationById(id: String): Destination? {
        return allDestinationsList.find { it.id == id }
    }
